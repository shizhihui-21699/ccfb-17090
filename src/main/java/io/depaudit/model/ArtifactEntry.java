package io.depaudit.model;

import java.util.List;
import java.util.Optional;

/**
 * One {@code <artifact name="...">} entry under a component.
 *
 * <p>A single artifact can carry several digests (e.g. both {@code sha1} and {@code sha256}),
 * several "also-trust" values for the same algorithm, and zero or more PGP key ids. The file
 * format allows all of these, and real projects use them, so the model must not flatten them.
 *
 * @param name    artifact file name, e.g. {@code commons-lang3-3.17.0.jar}
 * @param digests every digest recorded for this artifact, in document order
 * @param pgpKeys key ids (upper-cased hex fingerprints or long key ids) asserting a signature
 * @param line    1-based line of the {@code <artifact>} element in the source file, or 0 if unknown
 */
public record ArtifactEntry(
        String name,
        List<Digest> digests,
        List<String> pgpKeys,
        int line) {

    public ArtifactEntry {
        digests = digests == null ? List.of() : List.copyOf(digests);
        pgpKeys = pgpKeys == null ? List.of() : List.copyOf(pgpKeys);
    }

    /**
     * A single recorded hash value.
     *
     * @param algorithm the algorithm named by the element ({@code <sha256 .../>})
     * @param value     lower-cased hex digest
     * @param origin    the {@code origin} attribute if present. In Gradle's own writer this is a
     *                  prose marker such as {@code "Generated by Gradle"} — it is <em>not</em> a
     *                  repository URL, so a value that looks like a URL or a host name is itself
     *                  anomalous and is reported as {@link Provenance#DECLARED_ORIGIN}
     * @param reason    the optional {@code reason} attribute Gradle writes for auto-generated
     *                  entries, e.g. {@code "A key couldn't be downloaded"}
     * @param alsoTrust true when this value came from an {@code <also-trust>} child rather than
     *                  the element's own {@code value} attribute
     * @param line      1-based line of the digest element, or 0 if unknown
     */
    public record Digest(
            HashAlgorithm algorithm,
            String value,
            String origin,
            String reason,
            boolean alsoTrust,
            int line) {

        public Digest {
            value = value == null ? null : value.trim().toLowerCase(java.util.Locale.ROOT);
        }

        public boolean isWellFormed() {
            return algorithm != null && algorithm.looksWellFormed(value);
        }
    }

    public Optional<Digest> strongestDigest() {
        return digests.stream()
                .filter(d -> !d.alsoTrust())
                .filter(Digest::isWellFormed)
                .max(java.util.Comparator.comparingInt(d -> d.algorithm().strength()));
    }

    public List<Digest> digestsOf(HashAlgorithm algorithm) {
        return digests.stream().filter(d -> d.algorithm() == algorithm).toList();
    }

    /** True when the entry records at least one digest or PGP key, i.e. it asserts something. */
    public boolean isNotEmpty() {
        return !digests.isEmpty() || !pgpKeys.isEmpty();
    }

    public boolean isPom() {
        return name != null && name.endsWith(".pom");
    }
}
