package com.example.depreview.analyze;

import com.example.depreview.diff.UnifiedDiffParser;
import com.example.depreview.model.Finding;
import com.example.depreview.model.Severity;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Reviews security-control edits in Gradle verification metadata, not only component hashes.
 * Examples: disabling verification, adding wildcard trust rules, ignored keys or weak digests.
 */
public final class PolicyChangeAnalyzer {

    private static final Pattern HASH = Pattern.compile(
            "<(md5|sha1|sha256|sha512)\\b[^>]*\\bvalue=\"([^\"]+)\"", Pattern.CASE_INSENSITIVE);
    private static final Pattern PGP = Pattern.compile(
            "<(?:pgp|trusted-key)\\b[^>]*(?:value|id)=\"([^\"]+)\"", Pattern.CASE_INSENSITIVE);

    public List<Finding> analyze(UnifiedDiffParser.Patch patch) {
        List<Finding> findings = new ArrayList<>();
        int generatedOrigins = 0;
        String file = "gradle/verification-metadata.xml";

        for (UnifiedDiffParser.PatchFile patchFile : patch.files()) {
            String path = patchFile.newPath().isBlank() ? patchFile.oldPath() : patchFile.newPath();
            if (!path.endsWith("verification-metadata.xml") && !path.endsWith(".xml")) {
                continue;
            }
            file = path;
            for (UnifiedDiffParser.Hunk hunk : patchFile.hunks()) {
                for (UnifiedDiffParser.DiffLine line : hunk.lines()) {
                    if (line.kind() != UnifiedDiffParser.DiffLine.Kind.ADD || line.text() == null) {
                        continue;
                    }
                    String text = line.text().trim();
                    Integer lineNumber = line.newLine();
                    checkLine(text, path, lineNumber, findings);
                    if (text.contains("Generated by Gradle") && HASH.matcher(text).find()) {
                        generatedOrigins++;
                    }
                }
            }
        }

        if (generatedOrigins > 0) {
            findings.add(Finding.builder(
                            stableId(file, "generated-origin", generatedOrigins),
                            Severity.INFO,
                            "Added digests still carry the generated origin")
                    .file(file)
                    .addChange(generatedOrigins + " added hash line(s) use origin=\"Generated by Gradle\"")
                    .addEvidenceLine("These can be safe after repository/out-of-band confirmation; consider updating reviewed entries to Verified.")
                    .recommendation("Do not treat Gradle-generated origin text itself as human review evidence.")
                    .build());
        }
        return findings;
    }

    private void checkLine(String text, String file, Integer line, List<Finding> findings) {
        String lower = text.toLowerCase();
        if (lower.contains("<verify-metadata>false") || lower.contains("<verify-signatures>false")) {
            add(findings, Severity.CRITICAL, "Dependency verification was disabled",
                    file, line, text,
                    "Reject: this turns off the protection this file exists to enforce.");
        }

        if (lower.contains("<ignored-key")) {
            add(findings, Severity.HIGH, "A PGP key was added to ignored keys",
                    file, line, text,
                    "Confirm the key out-of-band; ignored keys can allow an unsigned or malicious artifact through.");
        }

        if (lower.startsWith("<trust ") || lower.contains("<trust ")) {
            boolean broad = lower.contains("regex=\".*\"") || lower.contains("regex=\".+\"")
                    || lower.contains("name=\".*\"") || lower.contains("group=\".*\"")
                    || lower.contains("regex=\"true\"");
            add(findings, broad ? Severity.CRITICAL : Severity.HIGH,
                    "A trusted-artifact bypass was added",
                    file, line, text,
                    broad
                            ? "Block broad/wildcard trust rules; they can verify nothing and may match dependency-confusion coordinates."
                            : "Review the exact coordinate/file scope and reason for this verification bypass.");
        }

        if (lower.contains("<trusted-key") && lower.contains("regex=")) {
            add(findings, Severity.HIGH, "A regex-scoped trusted key was added",
                    file, line, text,
                    "Ensure the regex is anchored and cannot match typosquatted or extra coordinates.");
        }

        if (lower.contains("<md5 ") || lower.contains("<md5>") || lower.contains("<sha1 ") || lower.contains("<sha1>")) {
            add(findings, Severity.MEDIUM, "Weak checksum algorithm added",
                    file, line, text,
                    "Require SHA-256 or SHA-512 for new metadata.");
        }

        Matcher hashMatcher = HASH.matcher(text);
        if (hashMatcher.find()) {
            String algorithm = hashMatcher.group(1).toLowerCase();
            String value = hashMatcher.group(2);
            int expectedLength = expectedHexLength(algorithm);
            if (expectedLength > 0 && value.matches("[0-9a-fA-F]+") && value.length() != expectedLength) {
                add(findings, Severity.MEDIUM, "Malformed " + algorithm + " checksum length",
                        file, line, text,
                        "Expected " + expectedLength + " hex characters but found " + value.length() + ".");
            }
        }

        Matcher pgpMatcher = PGP.matcher(text);
        if (pgpMatcher.find()) {
            String key = pgpMatcher.group(1);
            if (key.matches("[0-9a-fA-F]+") && key.length() < 40) {
                add(findings, Severity.LOW, "Short PGP identifier instead of full fingerprint",
                        file, line, text,
                        "Pin the full 40-character fingerprint to avoid short-ID collisions.");
            }
        }
    }

    private static int expectedHexLength(String algorithm) {
        return switch (algorithm) {
            case "md5" -> 32;
            case "sha1" -> 40;
            case "sha256" -> 64;
            case "sha512" -> 128;
            default -> -1;
        };
    }

    private static void add(
            List<Finding> findings,
            Severity severity,
            String title,
            String file,
            Integer line,
            String text,
            String recommendation) {
        String id = stableId(file, title, line == null ? text : line);
        Finding.Builder builder = Finding.builder(id, severity, title)
                .file(file)
                .addChange(text.length() > 500 ? text.substring(0, 500) + "…" : text)
                .recommendation(recommendation);
        if (line != null) {
            builder.addEvidenceLine("newLine=" + line);
        }
        findings.add(builder.build());
    }

    private static String stableId(String file, String kind, Object discriminator) {
        try {
            MessageDigest digest = MessageDigest.getInstance("SHA-256");
            byte[] hash = digest.digest((file + "|" + kind + "|" + discriminator)
                    .getBytes(StandardCharsets.UTF_8));
            return "POL-" + HexFormat.of().formatHex(hash).substring(0, 16);
        } catch (Exception e) {
            return "POL-" + Integer.toHexString((file + kind + discriminator).hashCode());
        }
    }
}
