package com.example.depreview.report;

import com.example.depreview.model.Finding;
import com.example.depreview.model.ReviewReport;
import com.example.depreview.model.Severity;
import com.example.depreview.model.VerifiedChange;

import java.util.Comparator;
import java.util.List;
import java.util.Map;

public final class MarkdownReporter {

    public String render(ReviewReport report) {
        StringBuilder out = new StringBuilder();
        out.append("## Dependency metadata review\n\n");
        out.append("**Verdict: ").append(escape(report.verdict())).append("**");
        if (report.failed()) {
            out.append(" — blocking findings at or above `")
                    .append(report.threshold())
                    .append("`");
        }
        out.append("\n\n");

        Map<Severity, Integer> counts = report.severityCounts();
        out.append("| Critical | High | Medium | Low | Info | Mutations | Verified artifacts |\n");
        out.append("|---:|---:|---:|---:|---:|---:|---:|\n");
        out.append("| ").append(counts.get(Severity.CRITICAL))
                .append(" | ").append(counts.get(Severity.HIGH))
                .append(" | ").append(counts.get(Severity.MEDIUM))
                .append(" | ").append(counts.get(Severity.LOW))
                .append(" | ").append(counts.get(Severity.INFO))
                .append(" | ").append(report.mutationCount())
                .append(" | ").append(report.verifiedUpgradeCount())
                .append(" |\n\n");

        if (!report.notices().isEmpty()) {
            out.append("> ").append(String.join("\n> ", report.notices())).append("\n\n");
        }

        List<Finding> findings = report.findings().stream()
                .sorted(Comparator.comparing(Finding::getSeverity).reversed()
                        .thenComparing(Finding::getId))
                .toList();

        List<Finding> blocking = findings.stream()
                .filter(f -> report.threshold() != null && report.threshold().blocks(f.getSeverity()))
                .toList();
        List<Finding> nonBlocking = findings.stream()
                .filter(f -> blocking.stream().noneMatch(b -> b.getId().equals(f.getId())))
                .toList();

        if (!blocking.isEmpty()) {
            out.append("### Blocking findings\n\n");
            for (Finding finding : blocking) {
                renderFinding(out, finding, true);
            }
        }

        if (!nonBlocking.isEmpty()) {
            out.append("<details><summary>Additional review items (")
                    .append(nonBlocking.size())
                    .append(")</summary>\n\n");
            for (Finding finding : nonBlocking) {
                renderFinding(out, finding, false);
            }
            out.append("</details>\n\n");
        }

        if (!report.verifiedChanges().isEmpty()) {
            renderVerified(out, report.verifiedChanges());
        }

        out.append("---\n");
        out.append("Generated by `dependency-metadata-review`. ");
        out.append("A match against a repository checksum proves consistency, not trust; review PGP fingerprints out-of-band.\n");
        return out.toString();
    }

    private void renderFinding(StringBuilder out, Finding f, boolean blocking) {
        out.append("#### ")
                .append(blocking ? ":no_entry: " : ":warning: ")
                .append('[').append(f.getSeverity()).append("] ")
                .append(escape(f.getTitle())).append("\n\n");
        out.append("- **ID:** `").append(f.getId()).append("`\n");
        out.append("- **Coordinate:** `").append(escape(f.coordinateLabel())).append("`\n");
        if (f.getArtifactName() != null && !f.getArtifactName().isBlank()) {
            out.append("- **Artifact:** `").append(escape(f.getArtifactName())).append("`\n");
        }
        if (f.getFile() != null && !f.getFile().isBlank()) {
            out.append("- **Metadata:** `").append(escape(f.getFile())).append("`\n");
        }
        if (f.getVerification() != null) {
            out.append("- **Verification:** `").append(f.getVerification().status()).append("`");
            if (f.getVerification().repositoryId() != null) {
                out.append(" via `").append(f.getVerification().repositoryId()).append("`");
            }
            out.append("\n");
        }
        if (!f.getChanges().isEmpty()) {
            out.append("\n**Changes**\n\n```text\n");
            for (String change : f.getChanges()) {
                out.append(change).append('\n');
            }
            out.append("```\n");
        }
        if (f.getRecommendation() != null && !f.getRecommendation().isBlank()) {
            out.append("\n**Recommendation:** ").append(escape(f.getRecommendation())).append("\n");
        }
        if (!f.getEvidenceLines().isEmpty()) {
            out.append("\n<details><summary>Evidence</summary>\n\n```text\n");
            f.getEvidenceLines().stream().limit(30).forEach(line -> out.append(line).append('\n'));
            out.append("```\n\n</details>\n");
        }
        out.append('\n');
    }

    private void renderVerified(StringBuilder out, List<VerifiedChange> verified) {
        out.append("<details><summary>Verified upgrade artifacts (")
                .append(verified.size())
                .append(")</summary>\n\n");
        out.append("These changes form normal version-upgrade pairs and matched an authorized repository.\n\n");
        int limit = 100;
        for (int i = 0; i < Math.min(limit, verified.size()); i++) {
            VerifiedChange v = verified.get(i);
            out.append("- `").append(escape(v.coordinate())).append("` — `")
                    .append(escape(v.artifactName())).append("` → `")
                    .append(v.repositoryId()).append("`/`")
                    .append(v.verificationStatus()).append("`\n");
        }
        if (verified.size() > limit) {
            out.append("- … and ").append(verified.size() - limit).append(" more\n");
        }
        out.append("\n</details>\n\n");
    }

    private static String escape(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("|", "\\|").replace("\n", " ");
    }
}
