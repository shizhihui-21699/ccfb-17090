package io.depaudit.verify;

import io.depaudit.diff.ChangeKind;
import io.depaudit.diff.MetadataChange;
import io.depaudit.model.ArtifactRef;
import io.depaudit.model.HashAlgorithm;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Tests the decision table that turns "this hash changed" into an actionable verdict.
 *
 * <p>These are the cases the problem statement calls out as hard: internal-only artifacts, the same
 * version legitimately built differently in different repositories, and distinguishing those from a
 * forged artifact that merely looks like a version bump.
 */
class ArtifactVerifierTest {

    private static final String GAV = "com.example:lib:1.0";
    private static final ArtifactRef COORDS = ArtifactRef.parse(GAV);
    private static final String FILE = "lib-1.0.jar";
    private static final HashAlgorithm ALG = HashAlgorithm.SHA256;
    private static final String NEW = "b".repeat(64);
    private static final String OLD = "a".repeat(64);
    private static final String OTHER = "c".repeat(64);

    private static final RepositoryConfig CENTRAL = new RepositoryConfig(
            "maven-central", "https://repo1.maven.org/maven2", TrustTier.CANONICAL, false);
    private static final RepositoryConfig MIRROR = new RepositoryConfig(
            "mirror", "https://mirror.example/maven2", TrustTier.MIRROR, false);
    private static final RepositoryConfig INTERNAL = new RepositoryConfig(
            "internal-nexus", "https://nexus.corp/repository/maven", TrustTier.INTERNAL, false);

    private static MetadataChange digestChange(ChangeKind kind, String oldValue, String newValue) {
        return new MetadataChange(
                kind, MetadataChange.Category.DIGEST,
                GAV + " " + FILE + " sha256", COORDS, FILE,
                new MetadataChange.Detail.DigestChange("sha256", oldValue, newValue,
                        "Generated by Gradle", "Generated by Gradle", false, false),
                MetadataChange.Severity.REVIEW, 10, 12);
    }

    private static VerificationPolicy policy(FakeRepositoryClient client,
                                            RepositoryConfig... repos) {
        return new VerificationPolicy(List.of(repos), client, false);
    }

    @Test
    void canonicalAgreementConfirms() {
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("maven-central", GAV, FILE, ALG, NEW);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.CONFIRMED_CANONICAL, r.verdict());
        assertEquals(TrustTier.CANONICAL, r.tier());
        assertFalse(r.isContradiction());
    }

    @Test
    void canonicalDisagreementIsContradiction() {
        // The canonical repository has this exact version, but with different bytes. This is the
        // forged-artifact signature and must block regardless of what any other repo says.
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("maven-central", GAV, FILE, ALG, OTHER);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.CONTRADICTED, r.verdict());
        assertTrue(r.isContradiction());
        assertTrue(joined(r).contains("canonical"), joined(r));
    }

    @Test
    void canonicalDisagreementWinsEvenWhenAMirrorAgrees() {
        // A forged artifact published to the organisation's mirror must not override the canonical
        // repository saying the release has different bytes.
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("maven-central", GAV, FILE, ALG, OTHER)
                .put("mirror", GAV, FILE, ALG, NEW);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL, MIRROR))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.CONTRADICTED, r.verdict(),
                "a mirror agreeing cannot launder a canonical contradiction");
    }

    @Test
    void internalOnlyArtifactIsNotSilentlyPassedOrFailed() {
        // The project publishes this artifact only to the internal repository. It cannot be checked
        // upstream at all, and the tool must say so rather than guess.
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("internal-nexus", GAV, FILE, ALG, NEW);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL, INTERNAL))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.INTERNAL_ONLY, r.verdict());
        assertEquals(TrustTier.INTERNAL, r.tier());
        assertFalse(r.isContradiction());
    }

    @Test
    void internalRepositoryDisagreementAfterOldValueMatchedIsContradiction() {
        // Yesterday the build resolved the artifact from the internal repository and the metadata
        // recorded that repo's digest. The merge request changes the digest to something that same
        // repository does not serve: whatever the canonical repository thinks, the build will now
        // fail, or (worse) resolve bytes nobody vouched for.
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("internal-nexus", GAV, FILE, ALG, OLD);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL, INTERNAL))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.CONTRADICTED, r.verdict());
        assertTrue(joined(r).contains("previous value matched"), joined(r));
    }

    @Test
    void mirrorAgreementConfirmsAtMirrorTierOnly() {
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("mirror", GAV, FILE, ALG, NEW);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL, MIRROR))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.CONFIRMED_MIRROR, r.verdict());
        assertEquals(TrustTier.MIRROR, r.tier());
    }

    @Test
    void nothingFoundAnywhereIsInconclusive() {
        FakeRepositoryClient c = new FakeRepositoryClient();
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.INCONCLUSIVE, r.verdict());
        assertFalse(r.isContradiction());
    }

    @Test
    void networkFailureIsInconclusiveNotFailure() {
        FakeRepositoryClient c = new FakeRepositoryClient()
                .fail("maven-central", new IOException("connection refused"));
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.INCONCLUSIVE, r.verdict(),
                "an unreachable repository must not be reported as a contradiction");
        assertTrue(joined(r).contains("connection refused"), joined(r));
    }

    @Test
    void offlineModeMakesNoCalls() {
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("maven-central", GAV, FILE, ALG, NEW);
        VerificationPolicy p = new VerificationPolicy(List.of(CENTRAL), c, true);
        VerificationResult r = new ArtifactVerifier(p)
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.INCONCLUSIVE, r.verdict());
        assertTrue(c.calls().isEmpty(), "offline must not touch the network: " + c.calls());
    }

    @Test
    void removedValueIsNotApplicable() {
        FakeRepositoryClient c = new FakeRepositoryClient();
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL))
                .verify(digestChange(ChangeKind.REMOVED, OLD, null));
        assertEquals(Verdict.NOT_APPLICABLE, r.verdict());
        assertTrue(c.calls().isEmpty());
    }

    @Test
    void nonDigestChangeIsNotApplicable() {
        FakeRepositoryClient c = new FakeRepositoryClient();
        MetadataChange toggle = new MetadataChange(
                ChangeKind.MODIFIED, MetadataChange.Category.VERIFICATION_TOGGLE,
                "verify-metadata", null, null,
                new MetadataChange.Detail.ToggleChange("verify-metadata", true, false),
                MetadataChange.Severity.BLOCKER, 0, 0);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL)).verify(toggle);
        assertEquals(Verdict.NOT_APPLICABLE, r.verdict());
    }

    @Test
    void onlyConfiguredRepositoriesAreConsulted() {
        // The repository list comes from the review environment, never from the file under review.
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("rogue", GAV, FILE, ALG, NEW);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertTrue(c.calls().stream().noneMatch(s -> s.contains("rogue")),
                "must never consult an unconfigured repository: " + c.calls());
        assertEquals(Verdict.INCONCLUSIVE, r.verdict());
    }

    @Test
    void conflictingRepositoriesAreDescribedNotCollapsed() {
        // Legitimate multi-repository publishing: the same version genuinely has different bytes in
        // two repositories. The report must show both, so a human can judge.
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("maven-central", GAV, FILE, ALG, OTHER)
                .put("mirror", GAV, FILE, ALG, NEW);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL, MIRROR))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        String evidence = joined(r);
        assertTrue(evidence.contains("maven-central"), evidence);
        assertTrue(evidence.contains("mirror"), evidence);
        assertTrue(evidence.contains("DIFFERENT"), evidence);
    }

    @Test
    void computeDigestHashesArtifactBytes() throws Exception {
        byte[] payload = "hello world".getBytes(java.nio.charset.StandardCharsets.UTF_8);
        FakeRepositoryClient c = new FakeRepositoryClient()
                .putArtifact("maven-central", GAV, FILE, payload);
        ArtifactVerifier v = new ArtifactVerifier(policy(c, CENTRAL));

        String expected = java.util.HexFormat.of().formatHex(
                java.security.MessageDigest.getInstance("SHA-256").digest(payload));
        assertEquals(java.util.Optional.of(expected),
                v.computeDigest(CENTRAL, COORDS, FILE, HashAlgorithm.SHA256));
    }

    @Test
    void computeDigestEmptyWhenArtifactMissing() throws Exception {
        FakeRepositoryClient c = new FakeRepositoryClient();
        ArtifactVerifier v = new ArtifactVerifier(policy(c, CENTRAL));
        assertTrue(v.computeDigest(CENTRAL, COORDS, FILE, HashAlgorithm.SHA256).isEmpty());
    }

    @Test
    void jcaNamesAreCorrect() {
        assertEquals("SHA-256", ArtifactVerifier.jcaName(HashAlgorithm.SHA256));
        assertEquals("SHA-512", ArtifactVerifier.jcaName(HashAlgorithm.SHA512));
        assertEquals("SHA-1", ArtifactVerifier.jcaName(HashAlgorithm.SHA1));
        assertEquals("MD5", ArtifactVerifier.jcaName(HashAlgorithm.MD5));
    }

    @Test
    void sha1OnlyConfirmationStillWorksButIsReportedAtItsTier() {
        FakeRepositoryClient c = new FakeRepositoryClient()
                .put("maven-central", GAV, FILE, HashAlgorithm.SHA1, "d".repeat(40));
        MetadataChange ch = new MetadataChange(
                ChangeKind.MODIFIED, MetadataChange.Category.DIGEST,
                GAV + " " + FILE + " sha1", COORDS, FILE,
                new MetadataChange.Detail.DigestChange("sha1", "e".repeat(40), "d".repeat(40),
                        null, null, false, false),
                MetadataChange.Severity.REVIEW, 1, 2);
        VerificationResult r = new ArtifactVerifier(policy(c, CENTRAL)).verify(ch);
        assertEquals(Verdict.CONFIRMED_CANONICAL, r.verdict());
    }

    @Test
    void signatureByTrustedKeyConfirmsArtifactNoRepositoryPublishes() throws Exception {
        // The internal-only case, resolved properly: no public checksum exists for these bytes, but
        // the artifact is signed by a key the reviewer pinned, AND the digest under review is the
        // digest of the signed bytes. That is a real confirmation.
        byte[] sig = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/payload.txt.asc"));
        byte[] key = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/test-key.asc"));
        byte[] signedPayload = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/payload.txt"));
        String realDigest = java.util.HexFormat.of().formatHex(
                java.security.MessageDigest.getInstance("SHA-256").digest(signedPayload));

        FakeRepositoryClient c = new FakeRepositoryClient()
                .putArtifact("internal-nexus", GAV, FILE, signedPayload)
                .putSignature("internal-nexus", GAV, FILE, sig);

        VerificationPolicy p = new VerificationPolicy(List.of(INTERNAL), c, false,
                io.depaudit.verify.pgp.KeySource.fixed("pinned", key));
        VerificationResult r = new ArtifactVerifier(p)
                .verify(digestChange(ChangeKind.MODIFIED, OLD, realDigest));

        assertEquals(Verdict.CONFIRMED_BY_SIGNATURE, r.verdict(), joined(r));
        assertTrue(joined(r).contains("signature by"), joined(r));
        assertTrue(joined(r).contains("hashes to the value under review"), joined(r));
    }

    @Test
    void validSignatureDoesNotConfirmAForgedDigest() throws Exception {
        // THE critical case. The repository serves a genuine, correctly signed artifact, but the
        // merge request records a different hash. A signature over the served bytes says nothing
        // about the recorded hash; confirming on it would pass exactly the attack this tool exists
        // to catch (write a wrong hash and dress it up as "signed").
        byte[] sig = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/payload.txt.asc"));
        byte[] key = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/test-key.asc"));
        byte[] signedPayload = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/payload.txt"));
        String forged = "f".repeat(64);

        FakeRepositoryClient c = new FakeRepositoryClient()
                .putArtifact("internal-nexus", GAV, FILE, signedPayload)
                .putSignature("internal-nexus", GAV, FILE, sig);

        VerificationPolicy p = new VerificationPolicy(List.of(INTERNAL), c, false,
                io.depaudit.verify.pgp.KeySource.fixed("pinned", key));
        VerificationResult r = new ArtifactVerifier(p)
                .verify(digestChange(ChangeKind.MODIFIED, OLD, forged));

        assertTrue(r.verdict() != Verdict.CONFIRMED_BY_SIGNATURE,
                "a valid signature over DIFFERENT bytes must not confirm the recorded hash");
        assertEquals(Verdict.INCONCLUSIVE, r.verdict(), joined(r));
        assertTrue(joined(r).contains("does not match"), joined(r));
    }

    @Test
    void signatureThatDoesNotVerifyDoesNotConfirm() throws Exception {
        byte[] sig = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/payload.txt.asc"));
        byte[] key = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/test-key.asc"));
        // Serve DIFFERENT bytes than the signature covers.
        FakeRepositoryClient c = new FakeRepositoryClient()
                .putArtifact("internal-nexus", GAV, FILE, "something else".getBytes())
                .putSignature("internal-nexus", GAV, FILE, sig);

        VerificationPolicy p = new VerificationPolicy(List.of(INTERNAL), c, false,
                io.depaudit.verify.pgp.KeySource.fixed("pinned", key));
        VerificationResult r = new ArtifactVerifier(p)
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertEquals(Verdict.INCONCLUSIVE, r.verdict(),
                "an invalid signature must not confirm anything: " + joined(r));
    }

    @Test
    void signaturesAreNotAttemptedWithoutAKeySource() throws Exception {
        byte[] sig = java.nio.file.Files.readAllBytes(
                java.nio.file.Path.of("src/test/resources/pgp/payload.txt.asc"));
        FakeRepositoryClient c = new FakeRepositoryClient()
                .putArtifact("internal-nexus", GAV, FILE, "x".getBytes())
                .putSignature("internal-nexus", GAV, FILE, sig);
        // No key source: signatures disabled.
        VerificationResult r = new ArtifactVerifier(new VerificationPolicy(List.of(INTERNAL), c, false))
                .verify(digestChange(ChangeKind.MODIFIED, OLD, NEW));

        assertTrue(c.calls().stream().noneMatch(s -> s.startsWith("signature")),
                "must not fetch signatures it cannot use: " + c.calls());
        assertEquals(Verdict.INCONCLUSIVE, r.verdict());
    }

    private static String joined(VerificationResult r) {
        return String.join(" | ", r.evidence());
    }
}
