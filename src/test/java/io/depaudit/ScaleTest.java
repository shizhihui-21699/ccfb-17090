package io.depaudit;

import io.depaudit.diff.MetadataChange;
import io.depaudit.diff.MetadataDiff;
import io.depaudit.diff.MetadataDiffer;
import io.depaudit.model.VerificationMetadata;
import io.depaudit.parse.VerificationMetadataParser;
import io.depaudit.report.AuditResult;
import io.depaudit.report.TextReportRenderer;
import io.depaudit.verify.HttpRepositoryClient;
import io.depaudit.verify.VerificationPolicy;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Scale tests for the central usability property: a large, routine dependency upgrade must produce
 * a short report, and a single planted edit inside it must still stand out.
 *
 * <p>These tests exist because the tool is only valuable if it stays readable on real files. A
 * thousands-of-lines metadata file with dozens of bumped dependencies is the normal case, not the
 * stress case, and a report that grows with the diff is the review blindness this tool is meant to
 * remove.
 */
class ScaleTest {

    /** Builds metadata XML for {@code count} dependencies, bumping the ones in {@code bumped}. */
    private static String metadata(int count, java.util.Set<Integer> bumped, int plantedIndex) {
        StringBuilder sb = new StringBuilder(256 * count);
        sb.append("""
                <?xml version="1.0" encoding="UTF-8"?>
                <verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
                   <configuration><verify-metadata>true</verify-metadata><verify-signatures>false</verify-signatures></configuration>
                   <components>
                """);
        for (int i = 0; i < count; i++) {
            String version = bumped.contains(i) ? "2.0" : "1.0";
            String digest = String.format("%064x", (i == plantedIndex ? 0xDEAD : i));
            sb.append("      <component group=\"com.example.g").append(i % 20)
                    .append("\" name=\"lib").append(i).append("\" version=\"").append(version)
                    .append("\">\n")
                    .append("         <artifact name=\"lib").append(i).append('-').append(version)
                    .append(".jar\">\n")
                    .append("            <sha256 value=\"").append(digest)
                    .append("\" origin=\"Generated by Gradle\"/>\n")
                    .append("         </artifact>\n")
                    .append("      </component>\n");
        }
        sb.append("   </components>\n</verification-metadata>\n");
        return sb.toString();
    }

    private static MetadataDiff diffOf(String oldXml, String newXml) throws Exception {
        VerificationMetadataParser p = new VerificationMetadataParser();
        VerificationMetadata o = p.parse(new java.io.ByteArrayInputStream(
                oldXml.getBytes(StandardCharsets.UTF_8)), "old.xml");
        VerificationMetadata n = p.parse(new java.io.ByteArrayInputStream(
                newXml.getBytes(StandardCharsets.UTF_8)), "new.xml");
        return new MetadataDiffer().diff(o, n);
    }

    @Test
    void fiftyBumpsAmongFourHundredDependenciesCorrelateCleanly() throws Exception {
        int deps = 400;
        java.util.Set<Integer> bumped = new java.util.HashSet<>();
        for (int i = 0; i < deps; i += 8) {
            bumped.add(i);   // 50 bumped dependencies
        }
        MetadataDiff d = diffOf(metadata(deps, java.util.Set.of(), -1), metadata(deps, bumped, -1));

        assertEquals(50, d.upgrades().size(), "one upgrade per bumped dependency");
        assertEquals(0, d.changes().size(),
                "a pure bump set is entirely correlation, not change noise: " + d.changes().size());
    }

    @Test
    void onePlantedEditStandsOutAmongFiftyBumps() throws Exception {
        int deps = 400;
        java.util.Set<Integer> bumped = new java.util.HashSet<>();
        for (int i = 0; i < deps; i += 8) {
            bumped.add(i);
        }
        int victim = 77;   // not in the bumped set: same version, digest swapped
        String oldXml = metadata(deps, java.util.Set.of(), -1);
        String newXml = metadata(deps, bumped, victim);

        MetadataDiff d = diffOf(oldXml, newXml);

        assertEquals(50, d.upgrades().size(), "the routine churn is still just upgrades");
        assertEquals(1, d.changes().size(),
                "exactly one change survives correlation — the planted edit: " + d.changes());
        assertTrue(d.changes().get(0).subject().contains("lib77"), d.changes().toString());
        assertTrue(d.changes().get(0).newLine() > 0);
    }

    @Test
    void largeReportStaysShort(@TempDir Path tmp) throws Exception {
        int deps = 400;
        java.util.Set<Integer> bumped = new java.util.HashSet<>();
        for (int i = 0; i < deps; i += 8) {
            bumped.add(i);
        }
        Path oldFile = tmp.resolve("old.xml");
        Path newFile = tmp.resolve("new.xml");
        Files.writeString(oldFile, metadata(deps, java.util.Set.of(), -1));
        Files.writeString(newFile, metadata(deps, bumped, 77));

        VerificationPolicy offline = new VerificationPolicy(
                java.util.List.of(), new HttpRepositoryClient(), true);
        AuditResult r = new AuditService().audit(oldFile, newFile, offline);

        ByteArrayOutputStream buf = new ByteArrayOutputStream();
        new TextReportRenderer(false, "gradle/verification-metadata.xml")
                .render(r, new PrintStream(buf, true, StandardCharsets.UTF_8));
        String report = buf.toString(StandardCharsets.UTF_8);
        long lines = report.lines().count();

        // The whole file diff is well over a thousand lines; the report must stay reviewable.
        assertTrue(lines < 300, "report was " + lines + " lines for a 400-dependency file");
        assertTrue(report.contains("lib77"), "the planted edit must be visible in the report");
        assertTrue(report.contains("BLOCKING") || report.contains("REVIEW"),
                "and it must be surfaced under a heading, not buried in a list");
    }

    @Test
    void parsingAndDiffingTenThousandComponentsIsFast() throws Exception {
        int deps = 10_000;
        String xml = metadata(deps, java.util.Set.of(), -1);
        long start = System.nanoTime();
        MetadataDiff d = diffOf(xml, xml);
        long ms = (System.nanoTime() - start) / 1_000_000;

        assertTrue(d.changes().isEmpty());
        assertTrue(ms < 20_000, "parsing+diffing 10k components took " + ms + " ms");
    }

    @Test
    void repeatedIdenticalBumpsDoNotExplodeChanges() throws Exception {
        // A real upgrade set often repeats the same GA across versions of a project; make sure the
        // correlation stays one-per-GA and does not degenerate into a cross product.
        int deps = 100;
        java.util.Set<Integer> bumped = java.util.Set.of(1, 2, 3);
        MetadataDiff d = diffOf(metadata(deps, java.util.Set.of(), -1), metadata(deps, bumped, -1));
        assertEquals(3, d.upgrades().size());
        assertEquals(0, d.changes().stream()
                .filter(c -> c.category() == MetadataChange.Category.COMPONENT).count());
    }
}
